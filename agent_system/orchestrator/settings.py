"""Orchestrator 멀티턴 설정 (여기서 True / False로 기능을 켜고 끕니다).

설정을 바꾼 뒤에는 봇(slack_bot.py / main.py)을 재시작하십시오.
"""

# ---------------------------------------------------------------------------
# 1. 다시 쓴 질문 표시
# ---------------------------------------------------------------------------
# True  : 후속 질문("남성은?")을 이전 대화를 반영해 다시 써서 분석했을 때,
#         Slack 답변 맨 위에 실제로 분석한 질문을 한 줄로 보여 줍니다.
#         예) 이전 대화를 반영해 "H&M 남성 상품 유형별 구매 Top 10"으로 분석했습니다.
# False : 표시하지 않습니다.
SHOW_REWRITTEN_QUESTION = True


# ---------------------------------------------------------------------------
# 2. 시간 기준 자동 리셋
# ---------------------------------------------------------------------------
# True  : 같은 대화(DM 사용자 / 채널 스레드)에서 마지막 메시지 후
#         AUTO_RESET_HOURS 시간이 지나 새 메시지가 오면, 이전 대화 기록과 직전 분석 요약을 지우고
#         새 대화로 시작합니다. (이전 조건이 잘못 이어지는 것을 막기 위함)
# False : 시간과 관계없이 대화를 계속 이어 갑니다.
AUTO_RESET_ENABLED = True
AUTO_RESET_HOURS = 12


# ---------------------------------------------------------------------------
# 3. 이전 저장본(checkpoint) 정리
# ---------------------------------------------------------------------------
# LangGraph는 실행 단계마다 대화 상태를 새로 저장하고 예전 저장본을 지우지 않습니다.
# 그래서 봇이 읽지 않는 기록(40개 초과분, 자동 리셋 전 대화)도
# runtime/conversation_memory.sqlite 파일에는 계속 남고 파일이 커집니다.
#
# True  : 매 턴이 끝나면 대화마다 최신 상태 1개만 남기고 예전 저장본을 삭제합니다.
#         (자동 리셋·40개 제한으로 지운 내용이 파일에서도 실제로 사라짐)
# False : 모든 저장본을 남깁니다. 개발 중 대화 이력 확인·디버깅용.
#         LangGraph의 get_state_history()로 턴별 상태를 다시 볼 수 있습니다.
PRUNE_OLD_CHECKPOINTS = False


# ---------------------------------------------------------------------------
# 4. 후속 질문에서 직전 그래프 형태 유지
# ---------------------------------------------------------------------------
# True  : 직전 분석이 그래프였고 후속 질문(예: "Top 5로 줄여줘")에 형태 지정이 없으면
#         다시 쓴 질문에 같은 그래프 종류("… 막대그래프로 보여줘")를 붙여 그래프를 다시 만듭니다.
#         사용자가 "표로", "그래프 없이"라고 하면 붙이지 않습니다.
#         (LLM이 다시 쓸 때 그래프 요청을 빠뜨리는 경우에 대비한 코드 보정입니다)
# False : LLM이 다시 쓴 질문을 그대로 사용합니다.
KEEP_PREVIOUS_CHART_TYPE = True


# ---------------------------------------------------------------------------
# 5. 채널에서 대화를 기억하는 범위
# ---------------------------------------------------------------------------
# CHANNEL_MEMORY_SCOPE
#   "channel" : 같은 채널이면 새 메시지로 @멘션해도 이어서 기억합니다. (스레드와 관계없음)
#               대화 ID = ch:<채널>:<사용자>
#   "thread"  : 봇 답변 스레드 안에서 이어 물을 때만 기억합니다. 새 메시지로 멘션하면 새 대화.
#               대화 ID = ch:<채널>:<스레드>:<사용자>
#
# CHANNEL_PER_USER
#   True  : 같은 채널(또는 스레드)이라도 사용자마다 따로 기억합니다.
#           예) A가 "여성 Top 10"을 물은 뒤 B가 "남성은?"이라고 하면 B에게는 이전 대화가 없어 되묻습니다.
#   False : 채널(또는 스레드) 참여자 전체가 한 대화를 공유합니다.
#
# DM은 이 설정과 관계없이 항상 사용자별입니다 (dm:<사용자>).
# 주의: 값을 바꾸면 대화 ID가 달라져 기존 채널 대화 기억은 이어지지 않습니다.
CHANNEL_MEMORY_SCOPE = "channel"
CHANNEL_PER_USER = True


# ---------------------------------------------------------------------------
# 6. 후속 질문은 직전과 같은 특화 Agent로 (Orchestrator)
# ---------------------------------------------------------------------------
# True  : 후속 질문(예: "남성은?")이면 Orchestrator가 LLM 판단 없이
#         직전 분석을 처리한 Agent로 보냅니다. (신제품 기획 결과의 후속 질문 → 신제품 기획 Agent)
# False : 후속 질문도 매번 Orchestrator(LLM)가 Agent를 새로 고릅니다.
# 등록된 Agent가 1개뿐이면 이 설정과 관계없이 그 Agent로 보냅니다.
KEEP_ROUTE_ON_FOLLOWUP = True


# ---------------------------------------------------------------------------
# 7. 확정값 저장 전 승인 받기 (check_approval)
# ---------------------------------------------------------------------------
# True  : "카테고리는 니트로 확정"처럼 확정값을 바꾸는 요청은 바로 저장하지 않고
#         승인 질문을 보낸 뒤 그래프를 멈춥니다(LangGraph interrupt).
#         다음 메시지가 '승인'이면 저장, '반려'면 저장 안 함, 수정 내용이면 기록 후 다시 요청 안내.
#         승인 대기 중 다른 질문을 하면 답한 뒤 승인 질문을 다시 붙입니다.
# False : 승인 없이 바로 저장합니다.
REQUIRE_APPROVAL_FOR_DECISIONS = True


# ---------------------------------------------------------------------------
# 8. 자동 리셋 때 확정값 유지
# ---------------------------------------------------------------------------
# True  : 12시간 자동 리셋 때 대화 기록·직전 분석만 지우고 확정값(campaign)과 승인 대기는 유지합니다.
# False : 확정값과 승인 대기도 함께 지웁니다.
KEEP_CAMPAIGN_ON_RESET = True
