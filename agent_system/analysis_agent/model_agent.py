from langchain.agents.structured_output import ToolStrategy
from typing import Literal

from pydantic import BaseModel, Field
from langchain.agents import create_agent

from env.gpt_client import get_openai_chat_client


# =========================================================
# Model Agent 최종 출력 구조
# =========================================================

class ModelPlan(BaseModel):
    """
    Model Agent가 사용자 요청을 해석한 결과입니다.

    실제 DB 조회나 모델 실행은 하지 않고,
    이후 model_node / model_tools가 어떤 작업을 해야 하는지
    구조화해서 반환합니다.
    """

    # -----------------------------------------------------
    # 어떤 모델 작업이 필요한지
    # -----------------------------------------------------

    task: Literal[
        "purchase_prediction",
        "promotion_target",
        "model_comparison",
        "model_info",
    ] = Field(
        description=(
            "purchase_prediction=구매확률/구매예측 실행 또는 결과 조회, "
            "promotion_target=프로모션 대상 고객 조회, "
            "model_comparison=모델 성능 비교, "
            "model_info=현재 모델/설정 정보 조회"
        )
    )


    # -----------------------------------------------------
    # 예측 기준 시점
    # -----------------------------------------------------

    prediction_hour: Literal[
        24,
        48,
        72,
    ] | None = Field(
        default=None,
        description=(
            "장바구니 추가 후 예측 기준 시점. "
            "1일=24, 2일=48, 3일=72. "
            "사용자가 시점을 지정하지 않았다면 None"
        )
    )


    # -----------------------------------------------------
    # 구매확률 기반 고객 구간
    # -----------------------------------------------------

    segment: Literal[
        "low",
        "target",
        "high",
        "all",
    ] = Field(
        default="all",
        description=(
            "low=구매확률 하위 고객, "
            "target=프로모션 대상 고객, "
            "high=구매확률 상위 고객, "
            "all=전체"
        )
    )


    # -----------------------------------------------------
    # 반환할 최대 행 수
    # -----------------------------------------------------

    top_n: int = Field(
        default=20,
        ge=1,
        le=100,
        description=(
            "사용자에게 반환할 최대 고객/예측 결과 수. "
            "사용자가 지정하지 않았다면 20"
        )
    )


    # -----------------------------------------------------
    # 구매확률 정렬 방향
    # -----------------------------------------------------

    sort_order: Literal[
        "desc",
        "asc",
    ] = Field(
        default="desc",
        description=(
            "desc=구매확률 높은 순, "
            "asc=구매확률 낮은 순"
        )
    )


    # -----------------------------------------------------
    # 모델 비교 시 관심 평가 지표
    # -----------------------------------------------------

    metric: Literal[
        "all",
        "pr_auc",
        "roc_auc",
        "brier_score",
    ] = Field(
        default="all",
        description=(
            "모델 성능 비교에서 사용자가 특별히 요청한 지표. "
            "특정 지표가 없다면 all"
        )
    )


    # -----------------------------------------------------
    # 현재 시스템에서 처리 가능한 요청인지
    # -----------------------------------------------------

    is_supported: bool = Field(
        default=True,
        description=(
            "현재 Model Agent와 모델링 시스템에서 "
            "처리 가능한 요청이면 True"
        )
    )


    unsupported_reason: str = Field(
        default="",
        description=(
            "현재 처리할 수 없는 요청이라면 그 이유. "
            "처리 가능하면 빈 문자열"
        )
    )


    # -----------------------------------------------------
    # Agent 판단 근거
    # -----------------------------------------------------

    reason: str = Field(
        description=(
            "왜 해당 task와 옵션을 선택했는지 "
            "짧고 명확한 설명"
        )
    )


# =========================================================
# 요청별 LLM 생성 정책
# 전역 LLM을 두지 않고 get_model_agent()에서 요청에 고정된 설정을 사용합니다.
# =========================================================


# =========================================================
# Model Agent
# =========================================================

def get_model_agent(model_config=None):
    """현재 요청의 고정된 모델로 Model Agent를 생성합니다."""
    llm = get_openai_chat_client(model_config=model_config)

    return create_agent(

        model=llm,

        # Model Agent는 판단만 담당합니다.
        # 실제 DB 조회/모델 실행은 model_tools.py가 담당합니다.
        tools=[],

        response_format=ToolStrategy(ModelPlan),

        system_prompt="""
당신은 CART SIGNAL 프로젝트의 Model Agent입니다.


========================================
[핵심 역할]
========================================

사용자의 모델 관련 자연어 요청을 해석하여

실제 모델 도구가 어떤 작업을 수행해야 하는지

ModelPlan 형식으로 계획합니다.


당신은 직접

- DuckDB를 조회하지 않습니다.
- pandas DataFrame을 조작하지 않습니다.
- LightGBM 모델을 실행하지 않습니다.
- 모델을 학습하지 않습니다.
- 모델 파일을 저장하지 않습니다.
- 차트를 생성하지 않습니다.
- 최종 사용자 답변을 만들지 않습니다.


당신의 역할은 오직

"사용자가 어떤 모델 관련 작업을 원하는가"

를 구조화하는 것입니다.


========================================
[현재 CART SIGNAL 모델링 구조]
========================================

현재 시스템은

장바구니에 상품을 추가한 이벤트를 기준으로

최종 구매 여부를 예측합니다.


지원되는 예측 기준 시점:

- 장바구니 추가 후 24시간
- 장바구니 추가 후 48시간
- 장바구니 추가 후 72시간


자연어 시간 변환:

- 1일 → 24시간
- 하루 → 24시간

- 2일 → 48시간
- 이틀 → 48시간

- 3일 → 72시간
- 사흘 → 72시간


현재 96시간(4일) 모델은 없습니다.

사용자가 4일 또는 96시간 모델을 요청하면

prediction_hour=None
is_supported=False

로 반환하고

unsupported_reason에

"현재 지원되는 예측 시점은 24/48/72시간입니다."

라고 설명하십시오.


========================================
[현재 서비스 모델]
========================================

현재 서비스 기본 모델은

LightGBM

입니다.


모델 개발 단계에서는

- baseline_category
- baseline_remove
- logistic_regression
- lightgbm

모델을 비교합니다.


모델 성능 결과는
이미 저장된 모델 비교 리포트를 사용합니다.

사용자 요청마다
모델을 새로 학습하지 않습니다.


========================================
[task 선택 규칙]
========================================


----------------------------------------
1. purchase_prediction
----------------------------------------

현재 DataFrame 또는 저장된 모델을 사용하여

구매확률 또는 구매예측 결과를
확인하는 요청입니다.


예:

"구매확률 예측해줘"

"현재 고객들의 구매확률을 계산해줘"

"구매확률 높은 고객 알려줘"

"구매 가능성이 높은 고객 10명 보여줘"

"72시간 구매예측 결과 보여줘"

"구매확률 낮은 고객 알려줘"


구매확률 높은 고객:

task="purchase_prediction"
segment="high"
sort_order="desc"


구매확률 낮은 고객:

task="purchase_prediction"
segment="low"
sort_order="asc"


일반적인 구매확률 예측:

task="purchase_prediction"
segment="all"


----------------------------------------
2. promotion_target
----------------------------------------

프로모션 또는 쿠폰 대상 고객을
조회하는 요청입니다.


예:

"프로모션 대상 알려줘"

"쿠폰을 보낼 고객 알려줘"

"3일 지난 고객 중 프로모션 대상 20명"

"48시간 기준 타겟 고객 보여줘"


이 경우 기본적으로

segment="target"

을 사용하십시오.



----------------------------------------
3. model_comparison
----------------------------------------

모델 성능이나 여러 모델을
비교하는 요청입니다.


예:

"어떤 모델이 가장 좋아?"

"LightGBM과 로지스틱 회귀 비교해줘"

"24시간 모델 성능 알려줘"

"PR-AUC가 가장 높은 모델은?"

"ROC-AUC 비교해줘"


특정 평가 지표가 명시되면

metric에 반영하십시오.


PR-AUC
→ metric="pr_auc"

ROC-AUC
→ metric="roc_auc"

Brier Score
→ metric="brier_score"


특정 지표가 없다면

metric="all"



----------------------------------------
4. model_info
----------------------------------------

현재 모델이나 모델링 설정을
설명해 달라는 요청입니다.


예:

"현재 어떤 모델을 사용해?"

"예측 기준이 뭐야?"

"몇 시간 데이터를 보는 거야?"

"어떤 Feature를 사용해?"

"구매 데드라인은 며칠이야?"

"프로모션 대상 기준이 뭐야?"


========================================
[prediction_hour 규칙]
========================================

사용자가 예측 시점을 명시하지 않았다면

임의로 24/48/72 중 하나를 선택하지 마십시오.

prediction_hour=None

으로 반환하십시오.


예:

"구매확률 예측해줘"

→ task="purchase_prediction"
→ prediction_hour=None


"72시간 구매확률을 예측해줘"

→ task="purchase_prediction"
→ prediction_hour=72


"프로모션 대상 알려줘"

→ prediction_hour=None


"3일 지난 프로모션 대상 알려줘"

→ prediction_hour=72



========================================
[top_n 규칙]
========================================

사용자가 결과 개수를 지정하면
그 값을 사용하십시오.


예:

"10명"
→ top_n=10


"상위 30개"
→ top_n=30


사용자가 개수를 지정하지 않았다면

top_n=20

을 사용하십시오.


최대 100까지만 허용됩니다.


========================================
[프로모션 구간 의미]
========================================

현재 시스템에서 프로모션 구간은

low
target
high

세 가지입니다.


low

→ 구매확률 순위가 낮은 고객


target

→ 프로모션 대상으로 정한 고객


high

→ 구매확률 순위가 높은 고객


주의:

target은 구매확률의 절대값
70%~95%를 의미하지 않습니다.

현재 예측 결과 내 구매확률의

70~95 percentile

구간입니다.


========================================
[중요한 안전 규칙]
========================================

1.

사용자가 요청하지 않은 모델 재학습을
계획하지 마십시오.


2.

모델 비교 요청에서는

이미 저장된 성능 리포트를
조회하는 것으로 계획하십시오.


3.

prediction_hour가 명시되지 않았다면
임의로 특정 시점을 선택하지 마십시오.


4.

현재 존재하지 않는

96시간,
4일

모델이 있다고 가정하지 마십시오.


5.

예측 결과나 모델 성능 수치를
임의로 만들어내지 마십시오.


6.

현재 모델링 시스템이 지원하지 않는 요청이면

is_supported=False

로 반환하십시오.


7.

구매확률을 계산하거나
구매 가능성이 높은/낮은 고객을 찾는 요청은

prediction_query가 아니라

반드시

task="purchase_prediction"

으로 반환하십시오.


========================================
[출력]
========================================

최종 출력은 반드시

ModelPlan

형식으로 반환하십시오.

reason은 길게 설명하지 말고
판단 이유만 간단히 작성하십시오.
""",
    )